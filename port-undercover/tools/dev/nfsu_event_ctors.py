"""Lists NFS Undercover's game events ("E..." classes) with the listed function that writes each one's vtable (its
constructor or factory), for core.nfsu's NFSU_EVENT_LOG diagnostic (mods/core/nfsu/events_table.inc).
An event's name getter is `MOV EAX, name; RET`; its vtable holds that getter in slot 2.
Usage: .venv/bin/python -I tools/dev/nfsu_event_ctors.py <nfs.exe> > mods/core/nfsu/events_table.inc"""
import bisect, re, struct, sys

d = open(sys.argv[1], 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
n = struct.unpack_from('<H', d, pe + 6)[0]
so = struct.unpack_from('<H', d, pe + 20)[0]
secs = []
for k in range(n):
    o = pe + 24 + so + 40 * k
    vs, va, rs, ro = struct.unpack_from('<IIII', d, o + 8)
    secs.append((va, rs, ro))


def off(v):
    for va, rs, ro in secs:
        if va <= v - 0x400000 < va + rs:
            return v - 0x400000 - va + ro


def foff(o):
    for va, rs, ro in secs:
        if ro <= o < ro + rs:
            return 0x400000 + va + o - ro


rows = [l.split('\t') for l in open('analysis/decompiled/nfs.exe/functions.tsv')]
fns = sorted((int(r[0], 16), int(r[2])) for r in rows if len(r) > 2 and r[2].isdigit())
keys = [s for s, _ in fns]
text_end = off(0xbd6000)
seen = {}
for m in re.finditer(rb'\xb8(....)\xc3', d[:text_end]):
    a = struct.unpack('<I', m.group(1))[0]
    o = off(a)
    if o is None:
        continue
    s = d[o:o + 64].split(b'\0')[0]
    if not re.fullmatch(rb'E[A-Z][A-Za-z0-9_]{3,}', s):
        continue
    g = foff(m.start())
    for r in re.finditer(re.escape(struct.pack('<I', g)), d):
        va = foff(r.start())
        if not va or va < 0xbd6000:
            continue
        vt = va - 8
        for c in re.finditer(re.escape(struct.pack('<I', vt)), d[:text_end]):
            ref = foff(c.start())
            i = bisect.bisect_right(keys, ref) - 1
            if i < 0:
                continue
            st, sz = fns[i]
            if ref < st + sz:
                names = seen.setdefault(st, [])
                if s.decode() not in names:
                    names.append(s.decode())
print('/* generated by tools/dev/nfsu_event_ctors.py: {listed function writing an event vtable, event name(s)} */')
for st in sorted(seen):
    print('    {0x%08xu, "%s"},' % (st, '/'.join(seen[st])))
